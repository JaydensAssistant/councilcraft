#!/usr/bin/env python3
"""PT41: copy the locked tip text (docs/tips/tips-locked-PT41.md) into councilcraft_tips.js.

Strips the display-only markers: '**[N]** ' (newcomer pool), ' ⚑' (check in game) and ' — 🔗 ...' (link note).
The border tip's number becomes {width}, filled at broadcast time (PT41 amendment 3a).
Run from the repo root: python3 pack/tools/mktips.py
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MD = ROOT / 'docs/tips/tips-locked-PT41.md'
JS = ROOT / 'pack/kubejs/server_scripts/councilcraft_tips.js'
BORDER = 'Our world border spans 10,000 blocks, centred on spawn.'


def tips():
    out = []
    for line in MD.read_text(encoding='utf-8').splitlines():
        m = re.match(r'^\| (\d+) \| (.+?) \| \d+ \|', line)
        if not m:
            continue
        num, text = int(m.group(1)), m.group(2)
        new = text.startswith('**[N]** ')
        text = text.removeprefix('**[N]** ')
        text = re.sub(r' — 🔗 .*$', '', text)
        text = text.removesuffix(' ⚑').strip()
        assert '⚑' not in text and '🔗' not in text and '[N]' not in text, text
        if text == BORDER:
            text = 'Our world border spans {width} blocks, centred on spawn.'
        out.append((num, new, text))
    return out


def main():
    t = tips()
    assert [n for n, _, _ in t] == list(range(1, 56)), 'expected tips 1..55'
    assert sum(1 for _, n, _ in t if n) == 13, 'expected 13 [N] tips'
    new = [x for _, n, x in t if n]
    gen = [x for _, n, x in t if not n]
    block = ('// BEGIN GENERATED by pack/tools/mktips.py from docs/tips/tips-locked-PT41.md. Do not edit by hand.\n'
             'const CC_NEW_TIPS = ' + json.dumps(new, ensure_ascii=False, indent=2) + '\n'
             'const CC_TIPS = ' + json.dumps(gen, ensure_ascii=False, indent=2) + '\n'
             '// END GENERATED\n')
    src = JS.read_text(encoding='utf-8')
    a, b = src.index('// BEGIN GENERATED'), src.index('// END GENERATED\n') + len('// END GENERATED\n')
    JS.write_text(src[:a] + block + src[b:], encoding='utf-8')
    print(f'{len(new)} newcomer + {len(gen)} general tips written to {JS.relative_to(ROOT)}')


if __name__ == '__main__':
    sys.exit(main())
