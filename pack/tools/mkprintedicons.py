"""PT48: build the muted printed-copy icons inside pack/resourcepacks/councilcraft-printed-copies.zip.

Every icon is derived at build time from a real source texture (never hand-copied into the repo):
  * minecraft:written_book, minecraft:name_tag      <- the vanilla 1.20.1 client jar (Mojang assets)
  * exposure:photograph, exposure:aged_photograph,
    exposure:signed_album                           <- the Exposure 1.9.22 jar (MIT license)
Only the 16x16 item icons change. Nothing here touches how a photo itself is drawn (frames, view screen, album
page, lectern); those do not use item icons.

Muting recipes (PT48):
  books / albums / other printed items: saturation x0.35, contrast x0.85 (around the icon's mean gray), then a
                                        15% blend toward (150, 135, 110)
  photographs (photograph, aged_photograph): brightness x0.75 only (no sepia, no aged look)
Alpha is kept as it is. The enchanted book icon (S210, enchanted_book_printed.png) is carried over untouched.

CIT Resewn matches each rule with  nbt.councilcraft\\:printed=regex:.*  exactly like printed_book_item.properties.
Items the Printer can mark that CIT cannot restyle are NOT covered (see docs/SPEC.md PT48 note): banners (built-in
entity renderer), stacked photographs (the variant depends on an NBT count CIT cannot read as a model predicate),
Create packages/schematics (Create Mod License not confirmed for modified redistribution).

Usage: python3 pack/tools/mkprintedicons.py [--vanilla-jar J] [--exposure-jar J] [--check]
  --check writes nothing and fails when the zip would change.
"""
