def mute_book(img):
    rgba = img.convert("RGBA")
    alpha = rgba.getchannel("A")
    rgb = rgba.convert("RGB")
    rgb = ImageEnhance.Color(rgb).enhance(0.35)
    rgb = ImageEnhance.Contrast(rgb).enhance(0.85)
    rgb = Image.blend(rgb, Image.new("RGB", rgb.size, TINT), 0.15)
    out = rgb.convert("RGBA")
    out.putalpha(alpha)
    return out


def dim_photo(img):
    rgba = img.convert("RGBA")
    alpha = rgba.getchannel("A")
    rgb = ImageEnhance.Brightness(rgba.convert("RGB")).enhance(0.75)
    out = rgb.convert("RGBA")
    out.putalpha(alpha)
    return out


def png_bytes(img):
    b = io.BytesIO()
    img.save(b, "PNG", optimize=True)
    return b.getvalue()


def properties(item, png):
    return (
        "# PT48: muted icon for printed copies (councilcraft:printed). The ':' inside the key MUST be escaped.\n"
        "type=item\n"
        f"items={item}\n"
        "nbt.councilcraft\\:printed=regex:.*\n"
        f"texture=./{png}.png\n"
        "weight=10\n"
    )


def build(vanilla_jar, exposure_jar):
    jars = {"vanilla": zipfile.ZipFile(vanilla_jar), "exposure": zipfile.ZipFile(exposure_jar)}
    existing = zipfile.ZipFile(ZIP)
    files = {}
    for name in existing.namelist():
        if name.endswith("/") or name in (CIT + "CREDITS.txt",):
            continue
        if any(name == CIT + o + ".png" or name == CIT + o + ".properties" for o, *_ in ICONS):
            continue
        files[name] = existing.read(name)
    for out, item, src, path, recipe in ICONS:
        img = Image.open(io.BytesIO(jars[src].read(path)))
        img = mute_book(img) if recipe == "book" else dim_photo(img)
        files[CIT + out + ".png"] = png_bytes(img)
        files[CIT + out + ".properties"] = properties(item, out).encode()
    files[CIT + "CREDITS.txt"] = CREDITS.encode()
    return files


def write(files):
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            zi = zipfile.ZipInfo(name, FIXED_TIME)
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, files[name])
    return b.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vanilla-jar", default=os.environ.get("CC_VANILLA_JAR", str(DEFAULT_VANILLA)))
    ap.add_argument("--exposure-jar", default=os.environ.get("CC_EXPOSURE_JAR", str(DEFAULT_EXPOSURE)))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = write(build(a.vanilla_jar, a.exposure_jar))
    if a.check:
        same = ZIP.read_bytes() == data
        print("OK: zip is up to date" if same else "DIFFERS: run mkprintedicons.py")
        sys.exit(0 if same else 1)
    ZIP.write_bytes(data)
    print(f"wrote {ZIP} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
