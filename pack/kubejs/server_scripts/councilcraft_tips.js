let ccTipTicks = 0

function ccTipUuid(p) { return String(p.getGameProfile().getId()) } // PT24: Rhino can't see Entity#getUUID

function ccTipsOff(server, p) {
  return server.persistentData.getCompound('cc_tips_off').getBoolean(ccTipUuid(p))
}

function ccTipsSetOff(server, p, off) {
  const d = server.persistentData
  const c = d.getCompound('cc_tips_off')
  if (off) c.putBoolean(ccTipUuid(p), true)
  else c.remove(ccTipUuid(p))
  d.put('cc_tips_off', c)
}

function ccTipActive(p) {
  return p.getTags().contains(CC_TIP_ACTIVE_TAG)
}

function ccTipWidth(server) {
  const d = server.persistentData
  const w = d.contains('cc_border_width') ? d.getInt('cc_border_width') : 0
  const n = w > 0 ? w : (typeof CC_BORDER_START !== 'undefined' ? CC_BORDER_START : CC_TIP_BORDER_FALLBACK)
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',')
}

function ccTipShuffle(size) {
  const bag = []
  for (let i = 0; i < size; i++) bag.push(i)
  // let, not const: KubeJS's Rhino binds a const in a loop body once, so every swap reused the first j and t
  // (0.4.18 smoke test: one tip repeated). Fisher-Yates needs fresh values each pass.
  for (let i = bag.length - 1; i > 0; i--) {
    let j = Math.floor(Math.random() * (i + 1))
    let t = bag[i]
    bag[i] = bag[j]
    bag[j] = t
  }
  return bag
}

// Draws the next tip for p, or null. Bags live in p.persistentData so they survive relogs and restarts.
function ccTipDraw(p) {
  const pd = p.persistentData
  const newcomer = !pd.getBoolean('cc_tips_new_done') && p.stats.playTime < CC_TIP_NEWCOMER_TICKS
  if (!newcomer && !pd.getBoolean('cc_tips_new_done')) pd.putBoolean('cc_tips_new_done', true)
  const kind = newcomer ? 'new' : 'all'
  const pool = newcomer ? CC_NEW_TIPS : CC_TIPS
  const key = 'cc_tips_bag_' + kind
  let bag = pd.getString(key) === '' ? [] : String(pd.getString(key)).split(',').map(s => parseInt(s, 10))
  bag = bag.filter(i => i >= 0 && i < pool.length)
  if (bag.length === 0) bag = ccTipShuffle(pool.length)
  const index = bag.pop()
  pd.putString(key, bag.join(','))
  if (newcomer && bag.length === 0) pd.putBoolean('cc_tips_new_done', true) // all [N] tips shown once
  return pool[index]
}

function ccTipSend(server, p) {
  const tip = ccTipDraw(p).replace('{width}', ccTipWidth(server))
  let body = Text.white(tip)
  if (tip.indexOf('/tips off') >= 0) body = body.clickRunCommand('/tips off').hover('Click to turn tips off')
  p.tell(Text.gold('Tip: ').append(body)
    .append(Text.darkGray(' [hide tips]').clickRunCommand('/tips off').hover('Type /tips on to bring them back')))
}

ServerEvents.tick(event => {
  const server = event.server
  const players = server.players
  if (players.isEmpty()) return // the clock only runs while someone is online
  if (++ccTipTicks < CC_TIP_INTERVAL) return
  ccTipTicks = 0
  players.forEach(p => {
    if (ccTipsOff(server, p)) return
    if (!ccTipActive(p)) return // AFK: this turn is skipped, not queued
    ccTipSend(server, p)
  })
})

ServerEvents.commandRegistry(event => {
  const { commands: Commands } = event
  event.register(Commands.literal('tips')
    .then(Commands.literal('off').executes(ctx => {
      const p = ctx.source.getPlayerOrException()
      ccTipsSetOff(ctx.source.server, p, true)
      ctx.source.sendSuccess(Text.of('Tips are off. Type /tips on to bring them back.'), false)
      return 1
    }))
    .then(Commands.literal('on').executes(ctx => {
      const p = ctx.source.getPlayerOrException()
      ccTipsSetOff(ctx.source.server, p, false)
      ctx.source.sendSuccess(Text.of('Tips are on.'), false)
      return 1
    })))
})
