ServerEvents.recipes(event => {
  event.remove({ type: 'betterend:infusion' })
  event.remove({ type: 'bclib:smithing' })
  event.remove({ type: 'minecraft:smithing_transform', mod: 'betterend' })
  event.remove({ id: /^betterend:(additional_(iron|gold|copper|netherite)|[a-z_]+_hammer_nugget_(smelting|blasting))$/ })
  CC_END_CUT.forEach(id => { event.remove({ output: id }); event.remove({ input: id }) })
  ;['thallasium', 'terminite'].forEach(m => {
    const I = 'betterend:' + m + '_ingot', S = 'minecraft:stick', id = s => 'councilcraft:betterend/' + m + '_' + s
    event.shaped('betterend:' + m + '_sword', ['I', 'I', 'S'], { I: I, S: S }).id(id('sword'))
    event.shaped('betterend:' + m + '_pickaxe', ['III', ' S ', ' S '], { I: I, S: S }).id(id('pickaxe'))
    event.shaped('betterend:' + m + '_axe', ['II', 'IS', ' S'], { I: I, S: S }).id(id('axe'))
    event.shaped('betterend:' + m + '_shovel', ['I', 'S', 'S'], { I: I, S: S }).id(id('shovel'))
    event.shaped('betterend:' + m + '_hoe', ['II', ' S', ' S'], { I: I, S: S }).id(id('hoe'))
    event.shaped('betterend:' + m + '_helmet', ['III', 'I I'], { I: I }).id(id('helmet'))
    event.shaped('betterend:' + m + '_chestplate', ['I I', 'III', 'III'], { I: I }).id(id('chestplate'))
    event.shaped('betterend:' + m + '_leggings', ['III', 'I I', 'I I'], { I: I }).id(id('leggings'))
    event.shaped('betterend:' + m + '_boots', ['I I', 'I I'], { I: I }).id(id('boots'))
  })
})

// Backstop: cut End items never exist as drops and are cleared from inventories (same pattern as CC_REMOVED_ITEMS).
EntityEvents.spawned(event => {
  if (String(event.entity.type) === 'minecraft:item' && CC_END_CUT.indexOf(String(event.entity.item.id)) >= 0) event.cancel()
})
PlayerEvents.tick(event => {
  const p = event.player
  if (p.age % 100 !== 50) return
  CC_END_CUT.forEach(id => { if (p.inventory.count(id) > 0) p.server.runCommandSilent('clear ' + p.username + ' ' + id) })
})
