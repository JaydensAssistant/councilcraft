package dev.councilcraft.rules;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Test;

/** 0.4.8: PPM70 offhand paraglider, resource pack order and fresh-install configs. */
class Release048RulesTest {
    @Test
    void mainHandParagliderWins() {
        assertEquals(ParagliderHand.Hand.MAIN, ParagliderHand.pick(true, true));
        assertEquals(ParagliderHand.Hand.MAIN, ParagliderHand.pick(true, false));
    }

    @Test
    void offhandParagliderGlidesWithAToolOrBlockInTheMainHand() {
        assertEquals(ParagliderHand.Hand.OFF, ParagliderHand.pick(false, true));
    }

    @Test
    void noParagliderInEitherHandMeansNoGlide() {
        // A paraglider only on a non-selected utility-belt slot is in neither hand.
        assertEquals(ParagliderHand.Hand.NONE, ParagliderHand.pick(false, false));
    }

    @Test
    void onlyTheStackInUseIsFlaggedAndOnlyWhileGliding() {
        assertTrue(ParagliderHand.flagged(true, true));
        assertFalse(ParagliderHand.flagged(true, false));
        assertFalse(ParagliderHand.flagged(false, true));
        assertFalse(ParagliderHand.flagged(false, false));
    }

    private static JsonObject yosbr(String file) throws IOException {
        return JsonParser.parseString(Files.readString(Path.of("pack/config/yosbr/config", file))).getAsJsonObject();
    }

    @Test
    void resourcePacksLoadInThePpm70Order() throws IOException {
        String line = Files.readAllLines(Path.of("pack/config/yosbr/options.txt")).stream()
            .filter(l -> l.startsWith("resourcePacks:")).findFirst().orElseThrow();
        List<String> packs = JsonParser.parseString(line.substring("resourcePacks:".length())).getAsJsonArray()
            .asList().stream().map(e -> e.getAsString()).toList();
        assertEquals(List.of("fabric", "continuity:default", "file/councilcraft-printed-copies.zip", "file/vanillatweaks-councilcraft.zip",
            "file/Better-Leaves-9.6.zip", "file/Antique_Atlas_4_Compat_v1.4.zip", "file/councilcraft-atlas-ru.zip", "punchy:punchy",
            "file/Modded Swords x Punchy! 1.20.1 - 1.21.1 v1.5.zip", "minecraft:supporteatinganimation", "file/FreshAnimations_v1.11.1_1.20+.zip",
            "vanillabackport:freshly_animated", "file/5.0 FA Illager Mod Compats.zip", "file/-1.21.2 Fresh Moves v3.1 (With Animated Eyes).zip",
            "file/Connected-Paths.zip", "file/Connected-Bricks.zip", "file/Connected-Rocks.zip", "file/councilcraft-connected-glass.zip",
            "file/councilcraft-bettergrass-ru.zip", "lambdabettergrass:default"), packs);
        java.util.Set<String> shipped = new java.util.HashSet<>();
        try (var files = Files.list(Path.of("pack/resourcepacks"))) {
            for (Path f : files.toList()) {
                String name = f.getFileName().toString();
                if (!name.endsWith(".pw.toml")) shipped.add(name);
                else Files.readAllLines(f).stream().filter(l -> l.startsWith("filename = "))
                    .forEach(l -> shipped.add(l.substring(12, l.length() - 1)));
            }
        }
        for (String pack : packs) {
            // Connected-*.zip are generated by Connected Paths on first launch (PPM29)
            if (pack.startsWith("file/") && !pack.startsWith("file/Connected-")) assertTrue(shipped.contains(pack.substring(5)), pack);
        }
    }

    @Test
    void freshMovesAndInventorioFreshInstallConfigs() throws IOException {
        assertEquals("ALL", yosbr("entity_texture_features.json").get("skinTransparencyMode").getAsString());
        assertTrue(yosbr("entity_model_features.json").get("preventFirstPersonHandAnimating").getAsBoolean());
        assertFalse(yosbr("inventorio.json").get("SkipEmptyUtilitySlots").getAsBoolean());
    }

    @Test
    void snowyFencesCarryTheLambdaBetterGrassNotice() throws IOException {
        try (var zip = new java.util.zip.ZipFile("pack/resourcepacks/councilcraft-bettergrass-ru.zip")) {
            long textures = zip.stream().filter(e -> e.getName().startsWith("assets/councilcraft/textures/block/fence/snowy_")).count();
            assertEquals(46, textures); // 22 Regions Unexplored woods + pale oak, post and side
            String license = new String(zip.getInputStream(zip.getEntry("LICENSE-LambdaBetterGrass.txt")).readAllBytes());
            assertTrue(license.contains("MIT") && license.contains("LambdAurora"));
        }
    }
}
